def rgb(h): h = h.lstrip('#'); return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))
def hsl(h):
    r, g, b = [v / 255 for v in rgb(h)]
    hh, l, s = colorsys.rgb_to_hls(r, g, b)
    return f"{round(hh*360,1):g} {round(s*100,1):g}% {round(l*100,1):g}%"
def lum(h):
    f = lambda c: c/12.92 if c <= .03928 else ((c+.055)/1.055)**2.4
    r, g, b = [f(v/255) for v in rgb(h)]
    return .2126*r + .7152*g + .0722*b
def cr(a, b):
    x, y = lum(a), lum(b); return (max(x, y)+.05)/(min(x, y)+.05)

def shadcn_block(n, a):
    """Map Stage onto the app's existing shadcn/Tailwind variable names (HSL triplets)."""
    H = lambda k: hsl(n[k]); A = lambda k: hsl(a[k])
    return [
      ('/* surfaces and type */', None),
      ('--canvas', H('bg')), ('--background', H('bg')), ('--foreground', H('text')),
      ('--surface', H('surface')), ('--surface-2', H('surface-2')), ('--surface-3', H('surface-3')),
      ('--card', H('surface-2')), ('--card-foreground', H('text')),
      ('--popover', H('surface-2')), ('--popover-foreground', H('text')),
      ('--muted', H('surface-2')), ('--muted-foreground', H('text-2')), ('--subtle-foreground', H('text-3')),
      ('--secondary', H('surface-2')), ('--secondary-foreground', H('text')),
      ('--accent', H('surface-3')), ('--accent-foreground', H('text')),
      ('--border', H('line')), ('--border-hover', H('line-strong')), ('--input', H('line-strong')),
      ('/* the brand accent (Ember or Mono) */', None),
      ('--brand', A('brand')), ('--brand-foreground', A('brand-foreground')),
      ('--brand-text', A('brand-text')), ('--brand-line', A('brand-line')),
      ('--primary', A('brand')), ('--primary-foreground', A('brand-foreground')), ('--ring', A('brand')),
      ('/* status: red means live (or an error), green means done */', None),
      ('--live', H('live')), ('--live-foreground', hsl('#ffffff')), ('--live-text', H('live-text')),
      ('--destructive', H('live')), ('--destructive-foreground', hsl('#ffffff')), ('--destructive-text', H('live-text')),
      ('--success', H('success')), ('--success-foreground', hsl('#07180f')), ('--success-text', H('success-text')),
      ('--warning', H('warning')), ('--warning-text', H('warning-text')),
      ('/* sidebar (desktop web) */', None),
      ('--sidebar-background', H('bg')), ('--sidebar-foreground', H('text-2')),
      ('--sidebar-primary', A('brand')), ('--sidebar-primary-foreground', A('brand-foreground')),
      ('--sidebar-accent', H('surface-2')), ('--sidebar-accent-foreground', H('text')),
      ('--sidebar-border', H('line')), ('--sidebar-ring', A('brand')),
    ]

def fmt(lines, indent='  '):
    out = []
    for k, v in lines:
        out.append(f"{indent}{k}" if v is None else f"{indent}{k}: {v};")
    return '\n'.join(out)

